static int hx8399c_unprepare(struct drm_panel *panel)
{
	struct hx8399c_panel *ctx = to_hx8399c_panel(panel);

	dev_info(&ctx->dsi->dev, "hx8399c_unprepare() start\n");

	mipi_dsi_dcs_set_display_off(ctx->dsi);
	msleep(20);
	mipi_dsi_dcs_enter_sleep_mode(ctx->dsi);
	msleep(120);

	dev_info(&ctx->dsi->dev, "hx8399c_unprepare() done\n");
	return 0;
}

