static int hx8399c_probe(struct mipi_dsi_device *dsi)
{
	struct hx8399c_panel *ctx;
	int ret;

	dev_info(&dsi->dev, "hx8399c_probe() called\n");

	dsi->lanes = 4;
	dsi->format = MIPI_DSI_FMT_RGB888;
	dsi->mode_flags = MIPI_DSI_MODE_VIDEO | MIPI_DSI_MODE_LPM; // | MIPI_DSI_MODE_VIDEO_HSE;
	dev_info(&dsi->dev, "DSI mode flags set\n");

	ctx = devm_kzalloc(&dsi->dev, sizeof(*ctx), GFP_KERNEL);
	if (!ctx)
		return -ENOMEM;

	ctx->dsi = dsi;

	dev_info(&dsi->dev, "Getting GPIOs from DT\n");
	ctx->reset_gpio = devm_gpiod_get(&dsi->dev, "reset", GPIOD_OUT_HIGH);
	if (IS_ERR(ctx->reset_gpio)) {
		dev_warn(&dsi->dev, "Reset GPIO not found\n");
		ctx->reset_gpio = NULL;
	}

	ctx->te_gpio = devm_gpiod_get(&dsi->dev, "te", GPIOD_IN);
	if (IS_ERR(ctx->te_gpio)) {
		dev_warn(&dsi->dev, "TE GPIO not found\n");
		ctx->te_gpio = NULL;
	}

	mipi_dsi_set_drvdata(dsi, ctx);



	drm_panel_init(&ctx->panel, &dsi->dev, &hx8399c_panel_funcs, DRM_MODE_CONNECTOR_DSI);
	drm_panel_add(&ctx->panel);
	dev_info(&dsi->dev, "Panel added to DRM\n");


	dev_info(&dsi->dev, "Attaching to DSI host...\n");
	ret = mipi_dsi_attach(dsi);
	if (ret < 0) {
		dev_err(&dsi->dev, "mipi_dsi_attach() failed: %d\n", ret);
		drm_panel_remove(&ctx->panel);
		return ret;
	}

	dev_info(&dsi->dev, "hx8399c_probe() done successfully\n");
	return 0;
}

static void hx8399c_remove(struct mipi_dsi_device *dsi)
{
	struct hx8399c_panel *ctx = mipi_dsi_get_drvdata(dsi);

	dev_info(&dsi->dev, "hx8399c_remove() called\n");

	drm_panel_remove(&ctx->panel);
	mipi_dsi_detach(dsi);

	dev_info(&dsi->dev, "hx8399c_remove() done\n");
}

